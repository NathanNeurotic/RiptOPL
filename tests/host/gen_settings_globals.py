#!/usr/bin/env python3
"""Emit definitions for every variable src/core/settings.cpp's table names, so the host test can link the real
table. Types/sizes come from the real headers (an int becomes `int x = <initialiser from the declaration site>`
only where the code owns it elsewhere, e.g. the coverflow values defined in themes.cpp: 3/30/..., see below)."""
import glob, re, sys, os
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
tbl = open(os.path.join(root, 'src/core/settings.cpp')).read()
hdrs = '\n'.join(open(p, errors='replace').read() for p in glob.glob(os.path.join(root, 'include/*.h')))
out = ['// generated by gen_settings_globals.py', '#include "include/opl.h"', '#include "include/themes.h"', '#include "include/favsupport.h"']
seen = set()
def decl_size(name):
    m = re.search(r'\b' + name + r'\[([^\]]+)\]', hdrs)
    return m.group(1) if m else None
for m in re.finditer(r'(intSetting|strSetting|colorSetting)\((\w+),\s*&?(\w+)', tbl):
    fn, key, var = m.groups()
    if var in seen: continue
    seen.add(var)
    ra = var in ('gRATelemetry', 'gRABadges')  # only declared in the RetroAchievements flavour
    line = (f'int {var};' if fn == 'intSetting' else f'char {var}[{decl_size(var) or 256}];' if fn == 'strSetting' else f'unsigned char {var}[3];')
    out.append(f'#ifdef RETROACHIEVEMENTS\n{line}\n#endif' if ra else line)
print('\n'.join(out))
